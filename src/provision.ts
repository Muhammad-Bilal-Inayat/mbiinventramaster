import { tenantDatabaseName, tenantDbPrefix, isTenantDatabaseName } from "./tenantDb.js";

// Phase 1: tenant provisioning for MariaDB only.
// All database credentials come from environment variables on the server
// where the database actually lives. This file never contains, reads, or
// logs a password, and it never accepts a database password from a request.
// The request only carries tenant/owner details; the server's own env
// supplies MARIADB_HOST / MARIADB_USER / MARIADB_PASSWORD.
//
// Safety rules applied here:
// - Database names are generated by the server (tenant_000001, ...), never
//   taken verbatim from a client, so no SQL identifier injection is possible.
// - Template SQL is applied statement-by-statement to the new tenant DB only.
// - If provisioning fails after CREATE DATABASE, the new database is left
//   in place and reported as an orphan. It is never auto-dropped, because
//   auto-drop is exactly how data gets lost on a partial failure.
// - The master tenants row and the tenant_user_index row are written last,
//   so a failed provision never advertises a tenant that has no database.

export interface ProvisionInput {
  name: string;
  plan: PlanId;
  ownerName: string;
  ownerLogin: string;
  ownerPassword: string;
  branchName: string;
  branchCity?: string;
}

export interface ProvisionResult {
  tenantId: string;
  databaseName: string;
  ownerUserId: string;
  branchId: string;
}

function mariadbConfig(database?: string) {
  // Trim connection values (NexPanel quirk: panel env lines written as
  // "KEY = value" arrive with spaces). The password is never trimmed:
  // passwords are opaque and may legitimately contain spaces.
  return {
    host: (process.env.MARIADB_HOST || "").trim() || undefined,
    port: Number((process.env.MARIADB_PORT || "").trim() || 3306),
    user: (process.env.MARIADB_USER || "").trim() || undefined,
    password: process.env.MARIADB_PASSWORD,
    database: database ? database.trim() : undefined,
    connectionLimit: 5,
  };
}

export async function provisionTenant(input: ProvisionInput): Promise<ProvisionResult> {
  if (!plans[input.plan]) throw new Error("INVALID_PLAN");
  await ensureMasterTables();
  const masterPool = mariadb.createPool(mariadbConfig((process.env.MARIADB_DATABASE || "").trim() || "master_control"));
  let tenantPool: ReturnType<typeof mariadb.createPool> | null = null;
  try {
    // Login must be unique across ALL tenants (tenant_user_index.login is
    // UNIQUE). Check first, before any database is created, so a duplicate
    // login can never leave an orphan tenant database behind. This was the
    // registration failure users saw as a generic 503: the index insert at
    // step 4 failed, after the tenant database was already seeded.
    const loginRows = (await masterPool.query("SELECT user_id FROM tenant_user_index WHERE login = ? LIMIT 1", [input.ownerLogin])) as any[];
    if (loginRows.length) throw new Error("LOGIN_ALREADY_EXISTS");

    // Next tenant number: never COUNT-based. COUNT breaks when a tenant row
    // was deleted, or when a failed provision left an orphan database behind
    // — a retry would reuse the same number and die on the already-seeded
    // users/ai_credits rows. Pick the first number whose master row AND
    // whose database both do not exist yet.
    const prefix = tenantDbPrefix();
    let existingSchemas = new Set<string>();
    try {
      const schemaRows = (await masterPool.query("SELECT SCHEMA_NAME AS name FROM INFORMATION_SCHEMA.SCHEMATA WHERE SCHEMA_NAME LIKE ?", [`${prefix}tenant_%`])) as any[];
      existingSchemas = new Set(schemaRows.map((r: any) => String(r.name)).filter((n) => isTenantDatabaseName(n)));
    } catch { /* schema listing is best-effort; the master-row check still applies */ }
    let next = 1;
    for (let attempt = 0; attempt < 1000; attempt++) {
      const candidate = tenantDatabaseName(next);
      const rowExists = (await masterPool.query("SELECT id FROM tenants WHERE id = ? LIMIT 1", [candidate])) as any[];
      if (!rowExists.length && !existingSchemas.has(candidate)) break;
      next += 1;
      if (attempt === 999) throw new Error("TENANT_NUMBER_EXHAUSTED");
    }
    const databaseName = tenantDatabaseName(next);
    const tenantId = databaseName;
    if (!isTenantDatabaseName(databaseName)) throw new Error("INVALID_DATABASE_NAME");

    // 1. Create the tenant database. Identifier is server-generated and
    // validated above, so backtick quoting here is safe.
    await masterPool.query(`CREATE DATABASE IF NOT EXISTS \`${databaseName}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);

    // 2. Apply the tenant template inside the new database only.
    tenantPool = mariadb.createPool(mariadbConfig(databaseName));
    const __dirname = path.dirname(fileURLToPath(import.meta.url));
    const templatePath = path.resolve(__dirname, "../db/migrations/002_tenant_template.sql");
    const template = await fs.readFile(templatePath, "utf-8");
    const statements = template.split(/;\s*\n/).map((s) => s.trim()).filter(Boolean);
    for (const statement of statements) {
      await tenantPool.query(statement);
    }

    // 3. Seed the tenant database: one branch, one owner, owner permissions.
    const branchId = randomId("branch");
    const ownerUserId = randomId("user");
    const passwordHash = await hashPassword(input.ownerPassword);
    const ownerPermissions = [
      "dashboard.view", "sales.view", "sales.create", "sales.refund", "sales.discount",
      "inventory.view", "inventory.edit", "inventory.adjust",
      "purchases.view", "purchases.create", "purchases.approve",
      "parties.view", "parties.payment", "reports.view", "reports.export",
      "transfers.request", "transfers.approve", "prescriptions.view", "prescriptions.create", "prescriptions.dispense", "attendance.view", "attendance.mark", "payroll.view", "accounting.view", "orders.view", "orders.manage",
      "admin.users", "admin.devices",
    ];
    await tenantPool.query(
      "INSERT INTO branches (id, name, city, active) VALUES (?, ?, ?, TRUE)",
      [branchId, input.branchName, input.branchCity || null],
    );
    await tenantPool.query(
      "INSERT INTO users (id, name, login, password_hash, role, active) VALUES (?, ?, ?, ?, 'Owner', TRUE)",
      [ownerUserId, input.ownerName, input.ownerLogin, passwordHash],
    );
    await tenantPool.query(
      "INSERT INTO user_branch_access (user_id, branch_id) VALUES (?, ?)",
      [ownerUserId, branchId],
    );
    for (const permission of ownerPermissions) {
      await tenantPool.query(
        "INSERT INTO user_permissions (user_id, permission_code) VALUES (?, ?)",
        [ownerUserId, permission],
      );
    }
    await tenantPool.query(
      "INSERT INTO tenant_settings (setting_key, setting_value) VALUES ('plan', ?) ON DUPLICATE KEY UPDATE setting_value = VALUES(setting_value)",
      [JSON.stringify(input.plan)],
    );
    // AI + home layout tables for the new tenant (also created on demand
    // by the store for older tenants, see migration 004).
    await tenantPool.query("CREATE TABLE IF NOT EXISTS home_layout (id INT PRIMARY KEY, layout_json JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP)");
    await tenantPool.query("CREATE TABLE IF NOT EXISTS ai_credits (id INT PRIMARY KEY, credits_total INT NOT NULL, credits_used INT NOT NULL DEFAULT 0, enabled TINYINT(1) NOT NULL DEFAULT 1, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP)");
    await tenantPool.query(
      "INSERT INTO ai_credits (id, credits_total, credits_used, enabled) VALUES (1, ?, 0, 1) ON DUPLICATE KEY UPDATE credits_total = VALUES(credits_total)",
      [plans[input.plan].aiQuota],
    );

    // 4. Master registry + login index, written last, in ONE transaction:
    // if the login index insert fails, the tenants row rolls back too.
    // A failed provision must never leave a tenant row that cannot log in.
    const branchSummary = JSON.stringify([{ id: branchId, name: input.branchName, city: input.branchCity || "" }]);
    const masterConn = await masterPool.getConnection();
    try {
      await masterConn.beginTransaction();
      await masterConn.query(
        "INSERT INTO tenants (id, name, database_name, plan, status) VALUES (?, ?, ?, ?, 'active')",
        [tenantId, input.name, databaseName, input.plan],
      );
      await masterConn.query(
        "INSERT INTO tenant_user_index (user_id, tenant_id, name, login, password_hash, role, branch_ids_json, permissions_json, active) VALUES (?, ?, ?, ?, ?, 'Owner', ?, ?, TRUE)",
        [ownerUserId, tenantId, input.ownerName, input.ownerLogin, passwordHash, JSON.stringify([branchId]), JSON.stringify(ownerPermissions)],
      );
      await masterConn.query(
        "UPDATE tenants SET branch_summary_json = ? WHERE id = ?",
        [branchSummary, tenantId],
      );
      await masterConn.commit();
    } catch (error) {
      await masterConn.rollback().catch(() => undefined);
      throw error;
    } finally {
      await masterConn.release();
    }

    // License Manager: every new tenant gets one active, lifetime
    // license matching its plan, with no expiry. Best-effort only: a
    // license failure must never roll back a tenant that was just created
    // (a tenant with no license record keeps working by design).
    try { await masterRegistry.createLicense({ tenantId, plan: input.plan, lifetime: true }); } catch (error) { console.warn("License auto-create failed for new tenant (tenant keeps working):", error instanceof Error ? error.message : error); }

    return { tenantId, databaseName, ownerUserId, branchId };
  } finally {
    if (tenantPool) await tenantPool.end().catch(() => undefined);
    await masterPool.end().catch(() => undefined);
  }
}

// Master diagnostics: proves whether THIS server's database user can
// create and use a tenant database — the exact capability public
// registration needs. Creates one random probe database, writes one row
// in it, then drops it in a finally block. Returns capability booleans
// and the failing step's error code only; no host, user, password or
// database name is ever returned or logged.
export interface DatabaseCreationProbe {
  prefix: string;
  canCreateDatabase: boolean;
  canUseDatabase: boolean;
  canWrite: boolean;
  failedStep: "create" | "use" | "write" | null;
  code: string | null;
}

export async function probeDatabaseCreation(): Promise<DatabaseCreationProbe> {
  const prefix = tenantDbPrefix();
  const probe = `${prefix}__mbi_probe_${crypto.randomBytes(6).toString("hex")}`;
  const registryPool = mariadb.createPool(mariadbConfig((process.env.MARIADB_DATABASE || "").trim() || "master_control"));
  const result: DatabaseCreationProbe = { prefix, canCreateDatabase: false, canUseDatabase: false, canWrite: false, failedStep: null, code: null };
  try {
    try {
      await registryPool.query(`CREATE DATABASE \`${probe}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
      result.canCreateDatabase = true;
    } catch (error) {
      result.failedStep = "create";
      result.code = (error as any)?.code ?? "UNKNOWN";
      return result;
    }
    const probePool = mariadb.createPool(mariadbConfig(probe));
    try {
      let conn: any;
      try {
        conn = await probePool.getConnection();
        result.canUseDatabase = true;
      } catch (error) {
        result.failedStep = "use";
        result.code = (error as any)?.code ?? "UNKNOWN";
        return result;
      }
      try {
        await conn.query("CREATE TABLE IF NOT EXISTS probe (id INT PRIMARY KEY)");
        await conn.query("INSERT INTO probe (id) VALUES (1)");
        await conn.query("SELECT id FROM probe WHERE id = 1");
        result.canWrite = true;
      } catch (error) {
        result.failedStep = "write";
        result.code = (error as any)?.code ?? "UNKNOWN";
        return result;
      } finally {
        conn.release();
      }
    } finally {
      await probePool.end().catch(() => undefined);
    }
    return result;
  } finally {
    await registryPool.query(`DROP DATABASE IF EXISTS \`${probe}\``).catch(() => undefined);
    await registryPool.end().catch(() => undefined);
  }
}
